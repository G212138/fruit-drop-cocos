const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('C:/ProgramData/cocos/editors/Creator/3.8.8/resources/app.asar.unpacked/node_modules/typescript');
const file = 'assets/app-bundle/app-view/page/game/native/expansion/board/GameBoard.ts';
const exportsObject = {};
const cc = {_decorator: {ccclass: () => value => value, property: () => () => {}}, Component: class {}};
const output = ts.transpileModule(fs.readFileSync(file, 'utf8'), {compilerOptions: {target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS, experimentalDecorators: true}}).outputText;
/** 边界模块仅提供构造器，测试实际棋盘的流程调度与输入门禁。 */
const imports = name => name === 'cc' ? cc : new Proxy({}, {get: () => class {}});
new Function('require', 'exports', output)(imports, exportsObject);
const board = new exportsObject.GameBoard();
const hint = {busy: true};
board.levelHintRoot = {getComponent: () => hint};
board.playing = true;
board.initialShiftPending = true;
const calls = [];
board.entry = {busy: true, tick: () => {calls.push('入场'); board.entry.busy = false;}};
board.shift = {busy: false, begin: () => calls.push('补位')};
board.spawner = {updateBlackHoles: () => {}, getWaiting: () => [], getFloorSnapshots: () => [], releaseBlackHole: () => calls.push('释放')};
board.failure = {tick: () => false};
board.warning = {tick: () => 'wait'};
board.matches = {drain: () => []};
board.lateUpdate(0.1);
board.release({waiting: true, spawning: false, iceLayers: 0, drop: () => calls.push('下落')});
assert.deepEqual(calls, [], '提示期间不能入场、补位或接受下落输入');
hint.busy = false;
board.lateUpdate(0.1);
assert.deepEqual(calls, ['入场']);
board.lateUpdate(0.1);
board.lateUpdate(0.1);
assert.deepEqual(calls, ['入场', '补位'], '补位在入场后且只触发一次');
board.initialShiftPending = true;
hint.busy = true;
board.lateUpdate(0.1);
assert.equal(calls.length, 2, '无需入场时也应等提示结束');
hint.busy = false;
board.lateUpdate(0.1);
assert.equal(calls.length, 3);
console.log('通过：真实棋盘提示、输入锁、入场、首次补位的顺序与零位移边界。');
